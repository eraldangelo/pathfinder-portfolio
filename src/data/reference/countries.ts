const allCountries: Country[] = [...priorityCountries, ...otherCountries];
const countryCodeMap = new Map(allCountries.map(c => [c.name, c.code]));
const normalizeCountryLookupKey = (value: unknown) =>
    String(value ?? '')
        .trim()
        .toLowerCase()
        .replace(/[’]/g, "'")
        .replace(/\./g, ' ')
        .replace(/[^a-z0-9' ]+/g, ' ')
        .replace(/\s+/g, ' ')
        .trim();

const canonicalCountryNameByKey = new Map(
    allCountries.map((country) => [normalizeCountryLookupKey(country.name), country.name]),
);
const countryAliasToCanonicalName = new Map(
    countryAliasPairs.map(([alias, countryName]) => [normalizeCountryLookupKey(alias), countryName]),
);

const resolveCanonicalCountryName = (countryName: string): string | undefined => {
    const key = normalizeCountryLookupKey(countryName);
    if (!key) return undefined;
    return countryAliasToCanonicalName.get(key) ?? canonicalCountryNameByKey.get(key);
};

export const getCanonicalCountryName = (countryName: string): string | undefined => {
    return resolveCanonicalCountryName(countryName);
};

export const getCountryCode = (countryName: string): string | undefined => {
    const canonicalCountryName = resolveCanonicalCountryName(countryName);
    if (!canonicalCountryName) return undefined;
    return countryCodeMap.get(canonicalCountryName);
};
